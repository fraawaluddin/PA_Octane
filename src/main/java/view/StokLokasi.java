    private void tampilkanIdentitasPengguna() {
        String namaPengguna = Session.namaLengkap;
        String peranPengguna = Session.peran;
        String lokasiPengguna = Session.lokasi;

        nama.setText(namaPengguna == null || namaPengguna.isBlank()
                ? "Pengguna" : namaPengguna);

        String identitasPeran = peranPengguna == null || peranPengguna.isBlank()
                ? "Belum ada sesi" : peranPengguna;

        if (lokasiPengguna != null && !lokasiPengguna.isBlank()) {
            identitasPeran += " · " + lokasiPengguna;
        }

        sebagai.setText(identitasPeran);
    }

    public void tampilDataStokLokasi() {
        DefaultTableModel model = new DefaultTableModel() {
            @Override public boolean isCellEditable(int row, int column) { return false; }
        };
        model.addColumn("ID STOK");
        model.addColumn("LOKASI PENYIMPANAN");
        model.addColumn("JENIS BBM");
        model.addColumn("JUMLAH STOK");
                model.addColumn("TERAKHIR DIPERBARUI");
        SimpleDateFormat sdf = new SimpleDateFormat("dd MMM yyyy HH:mm");
        try {
            for (model.StokRingkasModel stok : new controller.StokController()
                    .getStokPenyimpananByLokasi(Session.idLokasiPenyimpanan)) {
                model.addRow(new Object[]{stok.getIdStok(), stok.getNamaPemilik(),
                    stok.getNamaBbm(), String.format("%,.2f", stok.getJumlahStok()),
                    stok.getTerakhirDiperbarui() == null ? "-"
                            : sdf.format(stok.getTerakhirDiperbarui())});
            }
            table_stok_lokasi.setModel(model);
            TampilanTabel.rapikan(table_stok_lokasi);
            table_stok_lokasi.setRowHeight(30);
            table_stok_lokasi.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_ALL_COLUMNS);
            table_stok_lokasi.getColumnModel().getColumn(0).setPreferredWidth(100);
            table_stok_lokasi.getColumnModel().getColumn(1).setPreferredWidth(250);
            table_stok_lokasi.getColumnModel().getColumn(2).setPreferredWidth(200);
            table_stok_lokasi.getColumnModel().getColumn(3).setPreferredWidth(150);
            table_stok_lokasi.getColumnModel().getColumn(4).setPreferredWidth(238);
        } catch (SQLException | IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, "Gagal menampilkan data stok lokasi:\n" + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

