    private void loadSPBU() {
        DefaultComboBoxModel<String> model
                = new DefaultComboBoxModel<>();

        daftarSPBU.clear();
        model.addElement("Pilih SPBU...");

        try {
            for (SpbuModel spbu : new SpbuController().getSpbuAktif()) {
                String nama = spbu.getNamaSpbu();
                model.addElement(nama);
                daftarSPBU.put(nama, spbu.getIdSpbu());
            }
            cmbSPBU.setModel(model);
            cmbSPBU.setSelectedIndex(0);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Gagal memuat daftar SPBU: " + e.getMessage(),
                    "Kesalahan Database",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }
   
    
