    private void refreshActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_refreshActionPerformed
        javax.swing.JPanel panel = new javax.swing.JPanel(new java.awt.GridLayout(0, 2, 8, 8));
        javax.swing.JComboBox<String> bbm = new javax.swing.JComboBox<>();
        javax.swing.JComboBox<String> lokasi = new javax.swing.JComboBox<>();
        bbm.addItem("Semua");
        lokasi.addItem("Semua");
        try {
            for (String nama : laporanController.getNamaBbmAktif()) bbm.addItem(nama);
            for (String nama : laporanController.getNamaLokasiAktif()) lokasi.addItem(nama);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Daftar filter gagal dimuat: " + ex.getMessage());
            return;
        }
        bbm.setSelectedItem(filterBbm);
        lokasi.setSelectedItem(filterLokasi);
        javax.swing.JTextField awal = new javax.swing.JTextField(
                filterAwal == null ? "" : filterAwal.toString());
        javax.swing.JTextField akhir = new javax.swing.JTextField(
                filterAkhir == null ? "" : filterAkhir.toString());
        panel.add(new javax.swing.JLabel("Jenis BBM:"));
        panel.add(bbm);
        panel.add(new javax.swing.JLabel("Lokasi penyimpanan:"));
        panel.add(lokasi);
        panel.add(new javax.swing.JLabel("Tanggal awal (YYYY-MM-DD, kosong = semua):"));
        panel.add(awal);
        panel.add(new javax.swing.JLabel("Tanggal akhir (YYYY-MM-DD, kosong = semua):"));
        panel.add(akhir);
        int hasil = JOptionPane.showConfirmDialog(this, panel, "Filter Laporan",
                JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);
        if (hasil != JOptionPane.OK_OPTION) return;
        try {
            java.sql.Date tanggalAwal = awal.getText().isBlank() ? null
                    : java.sql.Date.valueOf(awal.getText().trim());
            java.sql.Date tanggalAkhir = akhir.getText().isBlank() ? null
                    : java.sql.Date.valueOf(akhir.getText().trim());
            if (tanggalAwal != null && tanggalAkhir != null && tanggalAwal.after(tanggalAkhir)) {
                throw new IllegalArgumentException("Tanggal awal tidak boleh melewati tanggal akhir.");
            }
            filterBbm = String.valueOf(bbm.getSelectedItem());
            filterLokasi = String.valueOf(lokasi.getSelectedItem());
            filterAwal = tanggalAwal;
            filterAkhir = tanggalAkhir;
            tampilDataKonfirmasi();
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, "Format filter tidak valid. Gunakan tanggal YYYY-MM-DD. "
                    + ex.getMessage(), "Filter Laporan", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_refreshActionPerformed

