    private void logout() {
        int konfirmasi = JOptionPane.showConfirmDialog(
                this,
                "Apakah Anda yakin ingin keluar dari sistem?",
                "Konfirmasi Logout",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE
        );

        if (konfirmasi == JOptionPane.YES_OPTION) {
            Session.clear();

            new Login().setVisible(true);
            this.dispose();
        }
    }

    private void tampilDataPenerimaan() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID PENERIMAAN");
        model.addColumn("JENIS BBM");
        model.addColumn("LOKASI PENYIMPANAN");
        model.addColumn("PETUGAS PENYIMPANAN");
        model.addColumn("TANGGAL PENERIMAAN");
        model.addColumn("JUMLAH DITERIMA");
        try {
            for (model.DaftarPenerimaanModel data : laporanController.getDaftarPenerimaan()) {
                model.addRow(new Object[]{data.idPenerimaan(), data.namaBbm(), data.namaLokasi(), data.namaPetugas(), data.tanggalPenerimaan(), data.jumlahDiterima()});
            }
            table_penerimaan.setModel(model);
            TampilanTabel.rapikan(table_penerimaan);
        } catch (java.sql.SQLException | IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, "Gagal menampilkan data penerimaan: " + e.getMessage(),
                    "Kesalahan", JOptionPane.ERROR_MESSAGE);
        }
    }

