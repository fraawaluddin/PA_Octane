    private void tampilDataStok(String keyword) {
        DefaultTableModel model = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
            @Override
            public Class<?> getColumnClass(int columnIndex) {
                switch (columnIndex) {
                    case 0: return Integer.class;
                    case 3: return java.math.BigDecimal.class;
                    case 4: return java.sql.Timestamp.class;
                    default: return String.class;
                }
            }
        };
        model.addColumn("ID STOK");
        model.addColumn("NAMA SPBU");
        model.addColumn("JENIS BBM");
        model.addColumn("JUMLAH STOK");
        model.addColumn("TERAKHIR DIPERBARUI");

        try {
            List<StokRingkasModel> daftar = stokController.getStokSpbu(keyword);
            for (StokRingkasModel stok : daftar) {
                model.addRow(new Object[]{
                    stok.getIdStok(),
                    stok.getNamaPemilik(),
                    stok.getNamaBbm(),
                    stok.getJumlahStok() == null ? java.math.BigDecimal.ZERO : stok.getJumlahStok(),
                    stok.getTerakhirDiperbarui()
                });
            }
            model.setColumnIdentifiers(new String[]{
                "ID STOK", "NAMA SPBU", "JENIS BBM",
                "JUMLAH STOK (LITER)", "TERAKHIR DIPERBARUI"
            });
            table_stok_spbu.setModel(model);
            konfigurasiTabelStok();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Gagal menampilkan data stok: " + e.getMessage(),
                    "Kesalahan",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }



